    function weatherInfo(code) {
        if (code === 0)  return [ICONS.sun,          'Clear'];
        if (code <= 2)   return [ICONS.partlyCloudy,  'Partly cloudy'];
        if (code === 3)  return [ICONS.cloudy,        'Overcast'];
        return                  [ICONS.rain,          'Rain'];
    }

    function londonTime() {
        return new Date().toLocaleTimeString('en-GB', {
            timeZone: 'Europe/London',
            hour:     '2-digit',
            minute:   '2-digit',
        });
    }

    async function initTooltip() {
        const tooltip = document.getElementById('london-tooltip');
        const iconEl  = document.getElementById('london-icon');
        const textEl  = document.getElementById('london-text');

        if (!tooltip || !iconEl || !textEl) return;

        try {
            const res  = await fetch(API_URL);
            const data = await res.json();
            const code = data.current.weathercode;
            const temp = Math.round(data.current.temperature_2m);
            const [svgIcon] = weatherInfo(code);
            const time = londonTime();

            iconEl.innerHTML   = svgIcon;
            textEl.textContent = `${time} · ${temp}°C`;
        } catch {
            tooltip.style.display = 'none';
        }
    }

